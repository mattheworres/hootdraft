<?php

/**
 * Turns docs/perf/results/<image>/<dataset>/*.json into docs/perf/RESULTS.md (numbers only; the write-up is in README.md).
 *   php docs/perf/report.php
 */

const REGRESSION_PERCENT = 20;
const REGRESSION_MS = 5;

$root = __DIR__ . '/results';
$md = "# Benchmark results\n\nGenerated by `report.php` from `docs/perf/results/`. Times are milliseconds on a laptop running Docker; compare within a table, not across machines.\nA regression is p95 more than " . REGRESSION_PERCENT . "% **and** more than " . REGRESSION_MS . " ms slower than the MyISAM run (real dataset only).\n";

$datasetOrder = ['real' => 0, '10000' => 1, '100000' => 2, '1000000' => 3];
$images = glob("$root/*", GLOB_ONLYDIR);
sort($images);

foreach ($images as $imageDir) {
  $datasets = array_map('basename', glob("$imageDir/*", GLOB_ONLYDIR));
  usort($datasets, fn ($a, $b) => ($datasetOrder[$a] ?? 9) <=> ($datasetOrder[$b] ?? 9));

  foreach ($datasets as $dataset) {
    $dir = "$imageDir/$dataset";
    if (!is_file("$dir/myisam.json") || !is_file("$dir/innodb.json")) {
      $md .= concurrentSection($dir, basename($imageDir), $dataset);
      continue;
    }
    $md .= section($dir, basename($imageDir), $dataset);
  }
}

file_put_contents(__DIR__ . '/RESULTS.md', $md);
echo "wrote docs/perf/RESULTS.md\n";

function load(string $dir, string $phase): ?array {
  $file = "$dir/" . preg_replace('/[^A-Za-z0-9_.-]+/', '_', $phase) . '.json';

  return is_file($file) ? json_decode(file_get_contents($file), true) : null;
}

function byId(array $run): array {
  return array_column($run['queries'], null, 'id');
}

function mb(int|string $bytes): string {
  return number_format($bytes / 1048576, 1);
}

function section(string $dir, string $image, string $dataset): string {
  $meta = json_decode(file_get_contents("$dir/meta.json"), true);
  $myisam = load($dir, 'myisam');
  $innodb = load($dir, 'innodb');
  $a = byId($myisam);
  $b = byId($innodb);

  $md = "\n## $image / $dataset\n\n";
  $md .= sprintf("Server %s. Seeded in %s s. In-place MyISAM→InnoDB conversion: **%s s**.\n\n", $myisam['version'], $meta['seed']['seconds'], $meta['migrate_convert']['seconds']);

  $md .= "| | MyISAM | InnoDB |\n|---|---|---|\n";
  $ma = $myisam['sizes']['pro_players'];
  $mb = $innodb['sizes']['pro_players'];
  $md .= sprintf("| rows (approx) | %s | %s |\n| data MB | %s | %s |\n| index MB | %s | %s |\n", number_format($ma['approx_rows']), number_format($mb['approx_rows']), mb($ma['data_bytes']), mb($mb['data_bytes']), mb($ma['index_bytes']), mb($mb['index_bytes']));
  $md .= sprintf("| CSV upload, %d rows, median ms | %s | %s |\n\n", $myisam['upload']['rows'], $myisam['upload']['median_ms'], $innodb['upload']['median_ms']);

  // Engine comparison
  $md .= "### Search latency, MyISAM → InnoDB (warm)\n\n| query | MyISAM p50 | InnoDB p50 | MyISAM p95 | InnoDB p95 | p95 change | cold first run (M→I) | verdict |\n|---|---|---|---|---|---|---|---|\n";
  $regressions = 0;
  foreach ($a as $id => $qa) {
    $qb = $b[$id];
    $diff = $qb['p95_ms'] - $qa['p95_ms'];
    $pct = $qa['p95_ms'] > 0 ? $diff / $qa['p95_ms'] * 100 : 0;
    $regression = $pct > REGRESSION_PERCENT && $diff > REGRESSION_MS;
    $regressions += $regression ? 1 : 0;
    $md .= sprintf("| %s | %.2f | %.2f | %.2f | %.2f | %+.0f%% | %.1f → %.1f | %s |\n", $id, $qa['p50_ms'], $qb['p50_ms'], $qa['p95_ms'], $qb['p95_ms'], $pct, $qa['cold_ms'], $qb['cold_ms'], $regression ? '**REGRESSION**' : '');
  }
  $md .= sprintf("\nRegressions by the rule: **%d** of %d queries.\n\n", $regressions, count($a));

  // Result differences
  $md .= "### Do the engines return the same results?\n\n| query | same 15 rows (as a set) | same order | rows in common | total matches (M / I) |\n|---|---|---|---|---|\n";
  $differing = 0;
  foreach ($a as $id => $qa) {
    $qb = $b[$id];
    $setSame = array_diff($qa['ids'], $qb['ids']) === [] && array_diff($qb['ids'], $qa['ids']) === [];
    $orderSame = $qa['ids'] === $qb['ids'];
    if ($orderSame && $qa['total_matches'] === $qb['total_matches']) {
      continue;
    }
    $differing++;
    $md .= sprintf("| %s | %s | %s | %d of %d | %d / %d |\n", $id, $setSame ? 'yes' : '**no**', $orderSame ? 'yes' : 'no', count(array_intersect($qa['ids'], $qb['ids'])), max(count($qa['ids']), count($qb['ids'])), $qa['total_matches'], $qb['total_matches']);
  }
  $md .= $differing === 0 ? "| all queries identical | | | | |\n" : '';
  $md .= sprintf("\n%d of %d queries differ in rows, order or match count.\n\n", $differing, count($a));

  // Candidate improvements
  $phases = ['innodb' => 'InnoDB as converted (reference)', 'innodb+ordered' => '+ ORDER BY last_name, first_name', 'innodb+prefix' => 'prefix match `term%` (report only)', 'innodb+prefix_fallback' => 'prefix, then substring if < 15 rows',
    'innodb+fulltext' => 'MATCH … AGAINST boolean `term*`', 'schema:varchar' => 'varchar columns + full league index', 'schema:composite' => '+ (league,last_name) and (league,first_name)',
    'schema:drop_fulltext' => '+ drop the two FULLTEXT indexes', 'schema:general_ci' => '+ utf8mb4_general_ci', 'tuned+ordered' => 'tuned schema + ORDER BY', 'tuned+prefix' => 'tuned schema + prefix', 'tuned+prefix_fallback' => 'tuned schema + prefix with fallback'];

  $md .= "### Candidate improvements (all on InnoDB; relative to the converted table)\n\n"
    . "Totals are over the 26 name-search queries (autocomplete, assumed-name and manual, both league sizes). \"big\" is the largest league, which is the scan-heavy case. \"lost matches\" counts queries whose total match count changed, i.e. recall lost or gained.\n\n"
    . "| candidate | sum p50 ms (all) | sum p50 ms (big league) | worst p95 ms | vs reference | lost matches | upload ms | index MB |\n|---|---|---|---|---|---|---|---|\n";

  $refTotal = null;
  foreach ($phases as $phase => $label) {
    $run = load($dir, $phase);
    if ($run === null) {
      continue;
    }
    $name = array_filter($run['queries'], fn ($q) => $q['kind'] !== 'pick_search');
    $sum = array_sum(array_column($name, 'p50_ms'));
    $big = array_sum(array_column(array_filter($name, fn ($q) => $q['class'] === 'big'), 'p50_ms'));
    $worst = max(array_column($name, 'p95_ms'));
    $refTotal ??= $sum;
    $lost = 0;
    foreach ($name as $q) {
      if ($q['total_matches'] !== $b[$q['id']]['total_matches']) {
        $lost++;
      }
    }
    $upload = isset($run['upload']) ? $run['upload']['median_ms'] : '';
    $md .= sprintf("| %s | %.1f | %.1f | %.1f | %+.0f%% | %d | %s | %s |\n", $label, $sum, $big, $worst, ($sum / $refTotal - 1) * 100, $lost, $upload, mb($run['sizes']['pro_players']['index_bytes']));
  }

  $md .= concurrentTable($dir);

  // Query plans for the engines
  $md .= "\n### Query plans (key used, rows estimated)\n\n| query | MyISAM | InnoDB |\n|---|---|---|\n";
  foreach ($a as $id => $qa) {
    if ($qa['kind'] === 'manual' || str_contains($id, 'small') || $qa['kind'] === 'pick_search') {
      continue;
    }
    $plan = fn (array $q) => sprintf('%s (%s, ~%s rows)', $q['explain'][0]['key'] ?? 'none', $q['explain'][0]['type'] ?? '?', $q['explain'][0]['rows'] ?? '?');
    $md .= sprintf("| %s | %s | %s |\n", $id, $plan($qa), $plan($b[$id]));
  }

  return $md . "\n";
}

/** The concurrent-reader table, or an empty string when the dataset has no concurrent run. */
function concurrentTable(string $dir): string {
  $md = '';
  $cm = load($dir, 'concurrent_myisam');
  $ci = load($dir, 'concurrent_innodb');
  if ($cm !== null && $ci !== null) {
    $md .= "\n### Concurrent readers (closed loop, the whole name-search mix, " . $cm['seconds'] . " s per level)\n\n| workers | MyISAM queries/s | InnoDB queries/s | MyISAM p95 / p99 ms | InnoDB p95 / p99 ms | MyISAM max ms | InnoDB max ms |\n|---|---|---|---|---|---|---|\n";
    foreach ($cm['levels'] as $i => $l) {
      $n = $ci['levels'][$i];
      $md .= sprintf("| %d | %s | %s | %.1f / %.1f | %.1f / %.1f | %s | %s |\n", $l['workers'], number_format($l['queries_per_second']), number_format($n['queries_per_second']), $l['p95_ms'], $l['p99_ms'], $n['p95_ms'], $n['p99_ms'], $l['max_ms'], $n['max_ms']);
    }
  }

  return $md;
}

function concurrentSection(string $dir, string $image, string $dataset): string {
  $table = concurrentTable($dir);

  return $table === '' ? '' : "\n## $image / $dataset (concurrent readers only)\n$table\n";
}
